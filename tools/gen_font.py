#!/usr/bin/env python3
"""Generates main/font5x7.c from the X11 misc-fixed 5x7 font (public domain).

Each glyph becomes 5 column bytes, bit 0 at the top: the SSD1306's page layout, so a
character is copied to the frame buffer without any bit shuffling.

Usage: tools/gen_font.py [/usr/share/fonts/X11/misc/5x7.pcf.gz] > main/font5x7.c
Needs Pillow.
"""
import gzip
import io
import sys

from PIL import PcfFontFile

FIRST, LAST = 0x20, 0x7E
W, H = 5, 7


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/X11/misc/5x7.pcf.gz"
    font = PcfFontFile.PcfFontFile(io.BytesIO(gzip.open(path).read()))
    print("/* Generated by tools/gen_font.py from the X11 misc-fixed 5x7 font (public")
    print(" * domain). Do not edit by hand. */")
    print('#include "font5x7.h"')
    print()
    print("const uint8_t font5x7[FONT5X7_LAST - FONT5X7_FIRST + 1][FONT5X7_W] = {")
    for code in range(FIRST, LAST + 1):
        glyph = font.glyph[code]
        img = glyph[3] if glyph else None
        if img is None or img.size != (W, H):
            sys.exit(f"glyph 0x{code:02x} is not {W}x{H}")
        cols = []
        for x in range(W):
            byte = 0
            for y in range(H):
                if img.getpixel((x, y)):
                    byte |= 1 << y
            cols.append(f"0x{byte:02x}")
        label = "' '" if code == 0x20 else ("'\\\\'" if code == 0x5C else ("'\\''" if code == 0x27 else f"'{chr(code)}'"))
        print(f"    {{{', '.join(cols)}}}, /* {label} */")
    print("};")


if __name__ == "__main__":
    main()
